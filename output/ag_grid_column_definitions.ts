/** Helper: build AG Grid applyColumnState array from a preset field list */
export function buildPresetState(
  allColDefs: ColDef[],
  visibleFields: string[]
): Array<{ colId: string; hide: boolean }> {
  return allColDefs
    .filter((col) => col.field !== undefined)
    .map((col) => ({
      colId: col.field as string,
      hide: !visibleFields.includes(col.field as string),
    }))
}

